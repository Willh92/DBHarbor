func resolveGoBin() string {
	if gr := strings.TrimSpace(runtime.GOROOT()); gr != "" {
		binName := "go"
		if runtime.GOOS == "windows" {
			binName = "go.exe"
		}
		candidate := filepath.Join(gr, "bin", binName)
		if st, err := os.Stat(candidate); err == nil && !st.IsDir() {
			return candidate
		}
	}
	return "go"
}

func locateGoOraConvertersFile() (string, error) {
	cmd := exec.Command(resolveGoBin(), "list", "-f", "{{.Dir}}", "github.com/sijms/go-ora/v2/converters")
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("locate go-ora converters dir: %w", err)
	}
	dir := strings.TrimSpace(string(out))
	target := filepath.Join(dir, "string_conversion_new.go")
	if _, err := os.Stat(target); err != nil {
		return "", fmt.Errorf("stat %s: %w", target, err)
	}
	return target, nil
}

func buildAllSpecs(origPath string) ([]*converterSpec, error) {
	rawSrc, err := os.ReadFile(origPath)
	if err != nil {
		return nil, err
	}
	ids, err := extractAllLangIDs(string(rawSrc))
	if err != nil {
		return nil, err
	}
	if len(ids) == 0 {
		return nil, fmt.Errorf("no langID cases found in %s", origPath)
	}

	var specs []*converterSpec
	for _, id := range ids {
		sp, ok := inspectConverter(id)
		if !ok {
			return nil, fmt.Errorf("NewStringConverter(%d) returned nil unexpectedly", id)
		}
		specs = append(specs, sp)
	}
	return specs, nil
}

func formatGoByteStringLiteral(data []byte) string {
	var sb strings.Builder
	sb.Grow(len(data)*4 + 128)
	sb.WriteByte('"')
	const hexDigits = "0123456789abcdef"
	for _, b := range data {
		sb.WriteByte('\\')
		sb.WriteByte('x')
		sb.WriteByte(hexDigits[b>>4])
		sb.WriteByte(hexDigits[b&0x0f])
	}
	sb.WriteByte('"')
	return sb.String()
}

func renderOverlayGoSource(gzData []byte) string {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by dbharbor/backend/cmd/gen-overlay; DO NOT EDIT.
package converters

import (
	"bytes"
	"compress/gzip"
	"encoding/binary"
	"errors"
	"io"
	"math"
	"sync"
)

type packedEntryLoc struct {
	metaOff   uint32
	slicesOff uint32
	keysOff   uint32
	valsOff   uint32
}

var (
	archiveOnce sync.Once
	rawArchive  []byte
	offsets     map[int]uint32
	entryLocs   []packedEntryLoc
	colMetaRef  []byte
	colSliceRef []byte
	colKeysRef  []byte
	colValsRef  []byte

	convCacheMu sync.RWMutex
	convCache   = make(map[int]*StringConverter)
)

const packedOracleCharsetsGzip = `)
	buf.WriteString(formatGoByteStringLiteral(gzData))
	buf.WriteString(`

var errUnsupportedOracleCharset = errors.New("unsupported charset")

func NewStringConverter(langID int) IStringConverter {
	switch langID {
	case 0x366, 0x367, 0x368, 0x369, 0x7D0, 0x7D2:
		return &StringConverter{
			LangID:    langID,
			CharWidth: 2,
			eReplace:  65533,
			dReplace:  63,
		}
	}

	convCacheMu.RLock()
	cached, ok := convCache[langID]
	convCacheMu.RUnlock()
	if ok && cached != nil {
		return cloneWithLeading(cached)
	}

	decoded, err := loadConverterFromPacked(langID)
	if err != nil || decoded == nil {
		return nil
	}
	convCacheMu.Lock()
	convCache[langID] = decoded
	convCacheMu.Unlock()
	return cloneWithLeading(decoded)
}

func cloneWithLeading(conv *StringConverter) IStringConverter {
	return &StringConverter{
		LangID:    conv.LangID,
		CharWidth: conv.CharWidth,
		eReplace:  conv.eReplace,
		dReplace:  conv.dReplace,
		dBuffer:   conv.dBuffer,
		dBuffer2:  conv.dBuffer2,
		eBuffer:   conv.eBuffer,
		leading:   conv.leading,
	}
}

func readPackedSvarint(b []byte, off *int) int {
	v, n := binary.Varint(b[*off:])
	if n <= 0 {
		return 0
	}
	*off += n
	return int(v)
}

func derivePackedBaseEBuffer(dBuffer, dBuffer2 []int) map[int]int {
	if len(dBuffer) == 0 {
		return nil
	}
	derived := make(map[int]int, len(dBuffer))
	if len(dBuffer2) == 0 {
		for b, u := range dBuffer {
			if u != 0xFFFF {
				if _, exists := derived[u]; !exists {
					derived[u] = b
				}
			}
		}
		return derived
	}
	maxIdx1 := 256
	if len(dBuffer) < maxIdx1 {
		maxIdx1 = len(dBuffer)
	}
	for idx1 := 0; idx1 < maxIdx1; idx1++ {
		base := dBuffer[idx1]
		if base == 0xFFFF {
			continue
		}
		for idx2 := 0; idx2 < 256; idx2++ {
			if base+idx2 >= len(dBuffer2) {
				break
			}
			u := dBuffer2[base+idx2]
			if u != 0xFFFF {
				ch := idx2
				if idx1 != 0 {
					ch = (idx1 << 8) | idx2
				}
				if _, exists := derived[u]; !exists {
					derived[u] = ch
				}
			}
		}
	}
	return derived
}

func mustUint32(n int) uint32 {
	if n < 0 || int64(n) > math.MaxUint32 {
		panic("integer out of uint32 range")
	}
	return uint32(n)
}

func initPackedArchive() {
	gr, err := gzip.NewReader(bytes.NewReader([]byte(packedOracleCharsetsGzip)))
	if err != nil {
		return
	}
	raw, err := io.ReadAll(gr)
	_ = gr.Close()
	if err != nil || len(raw) < 20 {
		return
	}

	count := int(binary.LittleEndian.Uint32(raw[0:4]))
	lenMeta := int(binary.LittleEndian.Uint32(raw[4:8]))
	lenSlices := int(binary.LittleEndian.Uint32(raw[8:12]))
	lenKeys := int(binary.LittleEndian.Uint32(raw[12:16]))
	lenVals := int(binary.LittleEndian.Uint32(raw[16:20]))
	if 20+lenMeta+lenSlices+lenKeys+lenVals > len(raw) {
		return
	}

	rawArchive = raw
	colMetaRef = rawArchive[20 : 20+lenMeta]
	colSliceRef = rawArchive[20+lenMeta : 20+lenMeta+lenSlices]
	colKeysRef = rawArchive[20+lenMeta+lenSlices : 20+lenMeta+lenSlices+lenKeys]
	colValsRef = rawArchive[20+lenMeta+lenSlices+lenKeys : 20+lenMeta+lenSlices+lenKeys+lenVals]

	offsets = make(map[int]uint32, count+16)
	entryLocs = make([]packedEntryLoc, 0, count)

	offMeta, offSlices, offKeys, offVals := 0, 0, 0, 0
	for i := 0; i < count; i++ {
		entryMetaStart := mustUint32(offMeta)
		entrySliceStart := mustUint32(offSlices)
		entryKeyStart := mustUint32(offKeys)
		entryValStart := mustUint32(offVals)
		entryIdx := mustUint32(len(entryLocs))
		entryLocs = append(entryLocs, packedEntryLoc{
			metaOff:   entryMetaStart,
			slicesOff: entrySliceStart,
			keysOff:   entryKeyStart,
			valsOff:   entryValStart,
		})

		numCases := readPackedSvarint(colMetaRef, &offMeta)
		for cIdx := 0; cIdx < numCases; cIdx++ {
			cid := readPackedSvarint(colMetaRef, &offMeta)
			offsets[cid] = entryIdx
		}
		_ = readPackedSvarint(colMetaRef, &offMeta) // fixedLang
		_ = readPackedSvarint(colMetaRef, &offMeta) // charWidth
		_ = readPackedSvarint(colMetaRef, &offMeta) // eReplace
		_ = readPackedSvarint(colMetaRef, &offMeta) // dReplace
		hasEBuf := readPackedSvarint(colMetaRef, &offMeta) == 1

		dLen := readPackedSvarint(colSliceRef, &offSlices)
		for j := 0; j < dLen; j++ {
			_ = readPackedSvarint(colSliceRef, &offSlices)
		}
		d2Len := readPackedSvarint(colSliceRef, &offSlices)
		for j := 0; j < d2Len; j++ {
			_ = readPackedSvarint(colSliceRef, &offSlices)
		}

		if hasEBuf {
			ovLen := readPackedSvarint(colKeysRef, &offKeys)
			for j := 0; j < ovLen; j++ {
				_ = readPackedSvarint(colKeysRef, &offKeys)
				_ = readPackedSvarint(colValsRef, &offVals)
			}
			remLen := readPackedSvarint(colKeysRef, &offKeys)
			for j := 0; j < remLen; j++ {
				_ = readPackedSvarint(colKeysRef, &offKeys)
			}
		}

		leadLen := readPackedSvarint(colKeysRef, &offKeys)
		for j := 0; j < leadLen; j++ {
			_ = readPackedSvarint(colKeysRef, &offKeys)
			_ = readPackedSvarint(colValsRef, &offVals)
		}
	}
}

func loadConverterFromPacked(targetLangID int) (*StringConverter, error) {
	archiveOnce.Do(initPackedArchive)
	if len(rawArchive) == 0 || offsets == nil {
		return nil, errUnsupportedOracleCharset
	}
	entryIdx, ok := offsets[targetLangID]
	if !ok || int(entryIdx) >= len(entryLocs) {
		return nil, errUnsupportedOracleCharset
	}

	loc := entryLocs[entryIdx]
	offMeta := int(loc.metaOff)
	offSlices := int(loc.slicesOff)
	offKeys := int(loc.keysOff)
	offVals := int(loc.valsOff)

	numCases := readPackedSvarint(colMetaRef, &offMeta)
	for cIdx := 0; cIdx < numCases; cIdx++ {
		_ = readPackedSvarint(colMetaRef, &offMeta)
	}
	fixedLang := readPackedSvarint(colMetaRef, &offMeta)
	charWidth := readPackedSvarint(colMetaRef, &offMeta)
	eReplace := readPackedSvarint(colMetaRef, &offMeta)
	dReplace := readPackedSvarint(colMetaRef, &offMeta)
	hasEBuf := readPackedSvarint(colMetaRef, &offMeta) == 1

	dLen := readPackedSvarint(colSliceRef, &offSlices)
	var dBuf []int
	if dLen > 0 {
		dBuf = make([]int, dLen)
	}
	prev := 0
	for j := 0; j < dLen; j++ {
		prev += readPackedSvarint(colSliceRef, &offSlices)
		dBuf[j] = prev
	}

	d2Len := readPackedSvarint(colSliceRef, &offSlices)
	var dBuf2 []int
	if d2Len > 0 {
		dBuf2 = make([]int, d2Len)
	}
	prev = 0
	for j := 0; j < d2Len; j++ {
		prev += readPackedSvarint(colSliceRef, &offSlices)
		dBuf2[j] = prev
	}

	var eBuf map[int]int
	if hasEBuf {
		ovLen := readPackedSvarint(colKeysRef, &offKeys)
		eBuf = derivePackedBaseEBuffer(dBuf, dBuf2)
		if eBuf == nil {
			eBuf = make(map[int]int, ovLen)
		}
		pk, pv := 0, 0
		for j := 0; j < ovLen; j++ {
			pk += readPackedSvarint(colKeysRef, &offKeys)
			pv += readPackedSvarint(colValsRef, &offVals)
			eBuf[pk] = pv
		}
		remLen := readPackedSvarint(colKeysRef, &offKeys)
		pk = 0
		for j := 0; j < remLen; j++ {
			pk += readPackedSvarint(colKeysRef, &offKeys)
			delete(eBuf, pk)
		}
	}

	leadLen := readPackedSvarint(colKeysRef, &offKeys)
	var leadMap map[int]int
	if leadLen > 0 {
		leadMap = make(map[int]int, leadLen)
	}
	pk, pv := 0, 0
	for j := 0; j < leadLen; j++ {
		pk += readPackedSvarint(colKeysRef, &offKeys)
		pv += readPackedSvarint(colValsRef, &offVals)
		leadMap[pk] = pv
	}

	resolvedLang := fixedLang
	if fixedLang < 0 {
		resolvedLang = targetLangID
	}
	return &StringConverter{
		LangID:    resolvedLang,
		CharWidth: charWidth,
		eReplace:  eReplace,
		dReplace:  dReplace,
		dBuffer:   dBuf,
		dBuffer2:  dBuf2,
		eBuffer:   eBuf,
		leading:   leadMap,
	}, nil
}
`)
	return buf.String()
}

func stageSlimGoOraModule(srcModDir, dstModDir string, slimConverterSrc []byte) error {
	_ = os.RemoveAll(dstModDir)
	err := filepath.WalkDir(srcModDir, func(srcPath string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, err := filepath.Rel(srcModDir, srcPath)
		if err != nil {
			return err
		}
		dstPath := filepath.Join(dstModDir, rel)
		if d.IsDir() {
			return os.MkdirAll(dstPath, 0o755)
		}
		if filepath.ToSlash(rel) == "converters/string_conversion_new.go" {
			if err := os.MkdirAll(filepath.Dir(dstPath), 0o755); err != nil {
				return err
			}
			return os.WriteFile(dstPath, slimConverterSrc, 0o644)
		}
		data, err := os.ReadFile(srcPath)
		if err != nil {
			return err
		}
		return os.WriteFile(dstPath, data, 0o644)
	})
	return err
}

func main() {
	outModFile := flag.String("out", "", "Output path for slim go.mod (e.g. .toolchain/build-overlay/go.slim.mod)")
	flag.Parse()
	if strings.TrimSpace(*outModFile) == "" {
		fmt.Fprintln(os.Stderr, "usage: gen-overlay -out <path/to/go.slim.mod>")
		os.Exit(1)
	}

	origPath, err := locateGoOraConvertersFile()
	if err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] %v\n", err)
		os.Exit(1)
	}
	specs, err := buildAllSpecs(origPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] build specs failed: %v\n", err)
		os.Exit(1)
	}
	gzData, err := packConverterSpecs(specs)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] pack specs failed: %v\n", err)
		os.Exit(1)
	}

	absMod, err := filepath.Abs(*outModFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] abs path failed: %v\n", err)
		os.Exit(1)
	}
	outDir := filepath.Dir(absMod)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] mkdir failed: %v\n", err)
		os.Exit(1)
	}

	oraModRoot := filepath.Dir(filepath.Dir(origPath))
	stagedOraDir := filepath.Join(outDir, "go-ora-v2")
	if err := stageSlimGoOraModule(oraModRoot, stagedOraDir, []byte(renderOverlayGoSource(gzData))); err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] stage slim go-ora failed: %v\n", err)
		os.Exit(1)
	}

	rawGoMod, err := os.ReadFile("go.mod")
	if err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] read go.mod failed: %v\n", err)
		os.Exit(1)
	}
	slimGoMod := string(rawGoMod) + fmt.Sprintf("\nreplace github.com/sijms/go-ora/v2 => %s\n", filepath.ToSlash(stagedOraDir))
	if err := os.WriteFile(absMod, []byte(slimGoMod), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "[gen-overlay] write slim modfile failed: %v\n", err)
		os.Exit(1)
	}

	if rawGoSum, err := os.ReadFile("go.sum"); err == nil {
		sumPath := strings.TrimSuffix(absMod, filepath.Ext(absMod)) + ".sum"
		if err := os.WriteFile(sumPath, rawGoSum, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "[gen-overlay] write slim go.sum failed: %v\n", err)
			os.Exit(1)
		}
	}

	fmt.Printf("[gen-overlay] Packed %d Oracle charsets into %.1f KB gzip slim modfile (%s)\n", len(specs), float64(len(gzData))/1024.0, absMod)
}
